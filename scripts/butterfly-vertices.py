"""Writes src/lib/specimens/butterfly-ring-vertices.ts from the original vertex file.

Source: public/butterfly-ring-vertices.json in ps2pdx/nertia at 58bd29ab (added in 26370e27, 11 April 2026),
the exported Blender mesh the Butterfly Ring loads: 19121 vertices, four decimals each, duplicates kept.
Every coordinate times 10000 fits an int16 exactly, so the module carries them losslessly as little-endian
int16 in base64 (about 73 KB gzipped, against 97 KB for the JSON). The ring imports it lazily.
Run from the repo root: python3 scripts/butterfly-vertices.py [path to nertia checkout]
"""
import base64, json, struct, subprocess, sys
from pathlib import Path

nertia = sys.argv[1] if len(sys.argv) > 1 else str(Path.home() / 'code/nertia')
raw = subprocess.run(['git', '-C', nertia, 'show', '58bd29ab:public/butterfly-ring-vertices.json'], check=True, capture_output=True).stdout
data = json.loads(raw)
flat = [c for v in data['vertices'] for c in v]
ints = [round(c * 10000) for c in flat]
assert len(data['vertices']) == data['vertexCount'] and all(abs(i) < 32768 and i / 10000 == c for i, c in zip(ints, flat))
b64 = base64.b64encode(struct.pack(f'<{len(ints)}h', *ints)).decode()
Path('src/lib/specimens/butterfly-ring-vertices.ts').write_text(
    '// Generated by scripts/butterfly-vertices.py from ps2pdx/nertia 58bd29ab:public/butterfly-ring-vertices.json.\n'
    f'// {data["vertexCount"]} vertices, x y z times 10000 as little-endian int16, base64.\n'
    f'export const VERTEX_COUNT = {data["vertexCount"]};\n'
    'export const SCALE = 1e-4;\n'
    f"export const VERTICES = '{b64}';\n")
print(data['vertexCount'], 'vertices')
